#!/usr/bin/env node
// Rebuilds art/ASSET_REGISTRY.json and docs/asset-registry.md from the data tables and what is on disk.
// Run: npm run assets
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const j = (p) => JSON.parse(readFileSync(resolve(root, p), "utf8"));
const has = (p) => !!p && existsSync(resolve(root, p));

const units = j("data/units/units.json");
const kingdom = j("data/kingdom/buildings.json");
const sideCards = j("data/cards/side_cards.json");

const rows = [];
const add = (group, id, label, kind, path, note = "") =>
  rows.push({ group, id, label, kind, path: path ?? null, status: has(path) ? "present" : "missing", note });

// --- unit art: every card wants a concept and a cut-out token ---
for (const u of units) {
  const base = `art/samples/${u.id}`;
  add("Units", u.id, u.name, "concept", `${base}_CONCEPT_V01.jpg`, `${u.stars ?? 1}★ ${u.faction}`);
  add("Units", u.id, u.name, "cutout", `${base}_CUTOUT_V01.png`, `${u.stars ?? 1}★ ${u.faction}`);
}
// --- buildings: one painting per visual tier ---
for (const [id, b] of Object.entries(kingdom.buildings)) {
  for (const band of kingdom.tierBands) {
    const p = (b.art ?? [])[band.tier - 1] ?? null;
    add("Buildings", `${id}_T${band.tier}`, `${b.name} tier ${band.tier}`, "building", p, `levels ${band.fromLevel}-${band.toLevel}`);
  }
}
// --- side cards borrow the art of what they summon, so only rituals with no result need their own ---
for (const c of sideCards) {
  if (c.kind === "fusion") { rows.push({ group: "Side cards", id: c.id, label: c.name, kind: "card", path: null, status: "derived", note: "shows its materials' art" }); continue; }
  add("Side cards", c.id, c.name, "card", `art/samples/${c.result}_CUTOUT_V01.png`, "ritual result");
}
// --- fixed interface and world art ---
for (const [id, label, p] of [
  ["MAP_WORLD", "Campaign map", "art/concepts/MAP_WORLD-CAMPAIGN_CONCEPT_V01.jpg"],
  ["MAP_SAMURAI", "Samurai province map", "art/concepts/MAP_SAMURAI-PROVINCE_CONCEPT_V01.jpg"],
  ["BASE_TOPDOWN", "Stronghold from above", "art/concepts/BASE_STRONGHOLD-TOPDOWN_CONCEPT_V01.jpg"],
  ["BASE_ANGLED", "Stronghold at an angle", "art/concepts/BASE_STRONGHOLD-ANGLED_CONCEPT_V01.jpg"],
  ["CARD_PAPER_PLAIN", "Card stock: plain linen paper (1-6 stars)", "art/ui/CARD-PAPER-PLAIN_V01.png"],
  ["CARD_PAPER_INKED", "Card stock: inked and taped (7-9 stars)", "art/ui/CARD-PAPER-INKED_V01.png"],
  ["CARD_PAPER_SEALED", "Card stock: sealed mulberry paper (10 stars and rites)", "art/ui/CARD-PAPER-SEALED_V01.png"],
  ["CARD_BACK", "Card back", "art/ui/CARD-BACK-PAPER_V01.png"],
  ["STAR_FILLED", "Star: earned", "art/ui/STAR_FILLED_V01.png"],
  ["STAR_EMPTY", "Star: unearned", "art/ui/STAR_EMPTY_V01.png"],
]) add("World and interface", id, label, "art", p);
for (const n of ["RES-KOKU","RES-IRON","RES-TIMBER","RES-SILVER","BLD-FORGE","BLD-RESEARCH","BLD-RECRUIT","BLD-BARRACKS","BLD-KEEP","UI-BANNER","UI-DRAW","BLD-BUILD"])
  add("Icons", n, n.replace(/-/g, " ").toLowerCase(), "icon", `art/ui/ICON_${n}_V01.png`);

const summary = {};
for (const r of rows) {
  summary[r.group] ??= { present: 0, missing: 0, derived: 0 };
  summary[r.group][r.status]++;
}
const total = { present: rows.filter((r) => r.status === "present").length, missing: rows.filter((r) => r.status === "missing").length };

writeFileSync(resolve(root, "art/ASSET_REGISTRY.json"), JSON.stringify({ generated: "npm run assets", total, summary, assets: rows }, null, 2) + "\n");

const md = [];
md.push("# Asset registry", "");
md.push("Generated by `npm run assets`. Do not edit by hand: it is rebuilt from the data tables and from what is on disk, so it can never drift from the game.", "");
md.push(`**${total.present} present, ${total.missing} still to paint.**`, "");
md.push("| Group | Present | Missing | Derived |", "|---|---:|---:|---:|");
for (const [g, s] of Object.entries(summary)) md.push(`| ${g} | ${s.present} | ${s.missing} | ${s.derived} |`);
md.push("", "## Still to paint", "");
md.push("| Group | Asset | Kind | Expected path | Note |", "|---|---|---|---|---|");
for (const r of rows.filter((r) => r.status === "missing")) md.push(`| ${r.group} | ${r.label} | ${r.kind} | \`${r.path ?? "—"}\` | ${r.note} |`);
md.push("", "## Present", "");
md.push("| Group | Asset | Kind | Path |", "|---|---|---|---|");
for (const r of rows.filter((r) => r.status === "present")) md.push(`| ${r.group} | ${r.label} | ${r.kind} | \`${r.path}\` |`);
writeFileSync(resolve(root, "docs/asset-registry.md"), md.join("\n") + "\n");

console.log(`asset registry: ${total.present} present, ${total.missing} missing`);
for (const [g, s] of Object.entries(summary)) console.log(`  ${g}: ${s.present} present, ${s.missing} missing`);
